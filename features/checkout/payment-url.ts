// Payment URLs come from the backend. Never navigate to inline data/JavaScript.
export function paymentRedirectUrl(value: unknown): string | null {
  if (typeof value !== "string" || !value) return null;
  try {
    const url = new URL(value);
    return url.protocol === "https:" && !url.username && !url.password ? url.href : null;
  } catch { return null; }
}
